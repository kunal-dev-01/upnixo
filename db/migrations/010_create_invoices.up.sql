-- ───────────────────────────────────────────────────────────────────
-- 1. ENUMS FOR INVOICE STATUS
-- ───────────────────────────────────────────────────────────────────
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'invoice_status') THEN
        CREATE TYPE invoice_status AS ENUM (
            'draft',            -- Generated but not yet finalized
            'issued',           -- Sent to the client, awaiting payment
            'paid',             -- Successfully paid
            'void'              -- Cancelled or invalidated
        );
    END IF;
END $$;

-- ───────────────────────────────────────────────────────────────────
-- 2. TABLE: invoices
-- ───────────────────────────────────────────────────────────────────
CREATE TABLE invoices (
    -- ── Identity ────────────────────────────────────────────────────
    id                              UUID            NOT NULL DEFAULT gen_random_uuid(),
    
    -- ── Relationships ───────────────────────────────────────────────
    client_id                       UUID            NOT NULL,
    -- Linking directly to the ledger transaction ensures strict financial tracking
    ledger_id                       UUID,

    -- ── Invoice Details ─────────────────────────────────────────────
    -- e.g., 'INV-2026-0001' (Must be universally unique)
    invoice_number                  VARCHAR(100)    NOT NULL,
    
    -- ── Financial Breakdown ─────────────────────────────────────────
    subtotal                        DECIMAL(15, 2)  NOT NULL,
    tax_amount                      DECIMAL(15, 2)  NOT NULL DEFAULT 0.00,
    total_amount                    DECIMAL(15, 2)  NOT NULL,
    currency                        CHAR(3)         NOT NULL DEFAULT 'USD',

    -- ── External Gateway (Paddle) ───────────────────────────────────
    paddle_invoice_id               VARCHAR(128),
    -- Stores the downloadable PDF link generated by Paddle or your own R2 bucket
    invoice_pdf_url                 TEXT,           

    -- ── Status & Timestamps ─────────────────────────────────────────
    status                          invoice_status  NOT NULL DEFAULT 'paid',
    issued_at                       TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    due_date                        TIMESTAMPTZ,    -- Nullable if paid immediately
    paid_at                         TIMESTAMPTZ,

    -- ── System Audit ────────────────────────────────────────────────
    created_at                      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at                      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),

    -- ── Constraints ─────────────────────────────────────────────────
    CONSTRAINT invoices_pkey PRIMARY KEY (id),
    CONSTRAINT invoices_number_unique UNIQUE (invoice_number),
    
    CONSTRAINT fk_invoice_client FOREIGN KEY (client_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_invoice_ledger FOREIGN KEY (ledger_id) REFERENCES payments_ledger(id) ON DELETE SET NULL,

    -- Math sanity check: Total must equal subtotal + tax
    CONSTRAINT chk_invoice_math CHECK (total_amount = subtotal + tax_amount)
);

-- ───────────────────────────────────────────────────────────────────
-- 3. INDEXES
-- ───────────────────────────────────────────────────────────────────

-- Fast lookup for a client's billing history page
CREATE INDEX idx_invoices_client_id 
    ON invoices (client_id, issued_at DESC);

-- Lookup by invoice number (Useful for support tickets)
CREATE INDEX idx_invoices_number 
    ON invoices (invoice_number);

-- Ensure we don't process the same Paddle invoice twice
CREATE INDEX idx_invoices_paddle_id 
    ON invoices (paddle_invoice_id) 
    WHERE paddle_invoice_id IS NOT NULL;

-- ── Trigger for updated_at ──────────────────────────────────────────
CREATE TRIGGER trg_invoices_updated_at
    BEFORE UPDATE ON invoices
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

-- ── Comments ─────────────────────────────────────────────────────────
COMMENT ON TABLE invoices IS 'Stores immutable billing records and PDF links for client transactions.';
COMMENT ON COLUMN invoices.ledger_id IS 'Foreign key linking the invoice to the actual movement of funds in payments_ledger.';